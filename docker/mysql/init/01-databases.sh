#!/bin/bash
set -e

mysql --protocol=socket -uroot --password="${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS taskflow_users CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS taskflow_tasks CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${TASKFLOW_DB_USER}'@'%' IDENTIFIED BY '${TASKFLOW_DB_PASSWORD}';
ALTER USER '${TASKFLOW_DB_USER}'@'%' IDENTIFIED BY '${TASKFLOW_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON taskflow_users.* TO '${TASKFLOW_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON taskflow_tasks.* TO '${TASKFLOW_DB_USER}'@'%';
FLUSH PRIVILEGES;
EOSQL
